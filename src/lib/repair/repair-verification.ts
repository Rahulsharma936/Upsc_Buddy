/**
 * R3.3 — Repair Verification
 *
 * Persists the outcome of a repair's verification MCQ as evidence.
 *
 * Pipeline position:
 *   R3.1 RepairRequest → R3.2 Repair (+ verification MCQ)
 *   → student answers → R3.3 buildRepairVerificationEvent()
 *   → revision_events (event_type = "repair_verification")
 *   → R3.4 re-diagnosis (future)
 *
 * This module is PURE: no DB, no AI, no side effects. The API route
 * supplies auth/ownership and performs the single append-only write.
 *
 * Architectural guarantees:
 *   - Does NOT touch SM-2. The produced event carries qualityRating: null
 *     and mcqCorrect: null so it can never enter a scheduling calculation
 *     or contaminate R2's MCQ accuracy features.
 *   - Does NOT use the legacy `src/lib/diagnostic/` scoring system.
 *   - `repairIntent` is DERIVED from the student's failureReason via the
 *     R3.1 mapping — never taken from the client.
 *   - `verificationCorrect` is DERIVED by comparing the submitted answer to
 *     the correct key — never taken from the client as a boolean.
 *   - The R3.1 `requestId` is preserved verbatim so the repair intervention
 *     and its verification remain correlated.
 *
 * @see repair-request.builder.ts (R3.1)
 * @see concept-teaching.executor.ts (R3.2a)
 */

import { z } from "zod";
import type { FailureReason } from "@/lib/evidence/evidence.types";
import { ALL_FAILURE_REASONS, getRepairIntent } from "./repair-request.builder";
import type { RepairIntent } from "./repair-request.builder";

// ─── Constants ──────────────────────────────────────────────

/**
 * The `revision_events.event_type` value for a repair verification.
 * Uses the existing table and existing JSONB metadata mechanism —
 * no new table, no migration, no schema change.
 */
export const REPAIR_VERIFICATION_EVENT_TYPE = "repair_verification";

/**
 * Repair intents that currently have an executor and therefore can
 * produce a verification MCQ.
 *
 * Verification is refused for any intent NOT listed here, because no repair
 * could have been generated for it — accepting one would fabricate evidence
 * about an intervention that never happened. This set grows as executors land:
 *   R3.2a → concept_teaching
 *   R3.5  → active_recall
 *   R3.6  → question_interpretation
 *   R3.7  → uncertainty_resolution
 *   R3.8  → calibration
 *   R3.9  → error_awareness
 */
export const VERIFIABLE_REPAIR_INTENTS: readonly RepairIntent[] = [
  "concept_teaching",
  "active_recall",
  "question_interpretation",
  "uncertainty_resolution",
  "calibration",
  "error_awareness",
];

/** Maximum stored length of the verification question text. */
const MAX_VERIFICATION_QUESTION_LENGTH = 1500;

// ─── Payload Schema ─────────────────────────────────────────

const answerKeySchema = z.enum(["a", "b", "c", "d"]);

const failureReasonSchema = z.enum(
  ALL_FAILURE_REASONS as unknown as [FailureReason, ...FailureReason[]],
);

/**
 * The accepted `POST /api/repair/verify` request body.
 *
 * `.strict()` — unknown client-supplied fields are rejected outright rather
 * than being silently carried into the stored evidence.
 *
 * Note what is deliberately NOT accepted:
 *   - `verificationCorrect` — derived server-side from the answer keys.
 *   - any SM-2 field (quality, interval, ease, repetitions, nextReviewAt).
 */
export const repairVerificationPayloadSchema = z
  .object({
    /** The R3.1 requestId of the repair being verified. Must survive intact. */
    requestId: z.uuid(),
    /** The concept the repair targeted. */
    conceptId: z.uuid(),
    /** The student's original self-reported cause. Authoritative signal. */
    failureReason: failureReasonSchema,
    /**
     * The intent the client believes it is verifying. Cross-checked against
     * the R3.1 mapping; the derived value is what gets stored.
     */
    repairIntent: z.string().min(1).max(64),
    /** The option the student picked on the verification MCQ. */
    verificationSelectedAnswer: answerKeySchema,
    /** The correct option for the verification MCQ, as generated by R3.2a. */
    verificationCorrectAnswer: answerKeySchema,
    /** Context about the ORIGINAL failed MCQ that triggered the repair. */
    questionContext: z
      .object({
        questionId: z.string().min(1).max(200).optional(),
        questionIndex: z.number().int().min(0).max(10_000).optional(),
      })
      .strict()
      .optional(),
    /** The verification question text, for later reconstruction of the loop. */
    verificationQuestion: z
      .string()
      .min(1)
      .max(MAX_VERIFICATION_QUESTION_LENGTH)
      .optional(),
  })
  .strict();

export type RepairVerificationPayload = z.infer<
  typeof repairVerificationPayloadSchema
>;

// ─── Stored Evidence Shape ──────────────────────────────────

/**
 * The exact JSONB written to `revision_events.event_metadata`.
 * Everything needed to reconstruct the repair loop later (R3.4).
 */
export interface RepairVerificationMetadata {
  /** R3.1 requestId — correlates this verification to its repair. */
  requestId: string;
  /** Concept the repair targeted. Mirrors the top-level column. */
  conceptId: string;
  /** Student's authoritative self-reported cause. */
  failureReason: FailureReason;
  /** Derived from failureReason via the R3.1 mapping. */
  repairIntent: RepairIntent;
  /** Whether the student answered the verification MCQ correctly. */
  verificationCorrect: boolean;
  /** The option the student selected. */
  verificationSelectedAnswer: "a" | "b" | "c" | "d";
  /** The correct option. */
  verificationCorrectAnswer: "a" | "b" | "c" | "d";
  /** Stable id of the ORIGINAL failed MCQ, when available. */
  questionId: string | null;
  /** Index of the ORIGINAL failed MCQ within the practice set. */
  questionIndex: number | null;
  /** The verification question text, when supplied. */
  verificationQuestion: string | null;
  /** Server-generated ISO timestamp of the verification. */
  verifiedAt: string;
}

/**
 * A ready-to-insert `revision_events` row for a repair verification.
 *
 * `qualityRating` and `mcqCorrect` are pinned to null so this row is inert
 * with respect to SM-2 and to R2's MCQ-derived features.
 */
export interface RepairVerificationEvent {
  eventType: typeof REPAIR_VERIFICATION_EVENT_TYPE;
  qualityRating: null;
  mcqCorrect: null;
  mcqQuestionIndex: null;
  eventMetadata: RepairVerificationMetadata;
}

// ─── Validation ─────────────────────────────────────────────

export type RepairVerificationValidation =
  | { success: true; payload: RepairVerificationPayload; repairIntent: RepairIntent }
  | { success: false; error: string };

/**
 * Validate an untrusted `POST /api/repair/verify` body.
 *
 * Beyond schema validation this enforces two invariants the client cannot
 * be trusted with:
 *   1. `repairIntent` must equal the R3.1 mapping of `failureReason`.
 *   2. That intent must have an executor (i.e. a repair could really exist).
 *
 * @param body - Untrusted request body
 */
export function validateRepairVerification(
  body: unknown,
): RepairVerificationValidation {
  const parsed = repairVerificationPayloadSchema.safeParse(body);

  if (!parsed.success) {
    const detail = parsed.error.issues
      .map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`)
      .join("; ");
    return { success: false, error: `Invalid repair verification payload — ${detail}` };
  }

  const payload = parsed.data;

  // The student's failureReason is authoritative; the intent follows from it.
  const derivedIntent = getRepairIntent(payload.failureReason);

  if (payload.repairIntent !== derivedIntent) {
    return {
      success: false,
      error:
        `repairIntent "${payload.repairIntent}" does not match the repair intent for ` +
        `failureReason "${payload.failureReason}" (expected "${derivedIntent}")`,
    };
  }

  if (!VERIFIABLE_REPAIR_INTENTS.includes(derivedIntent)) {
    return {
      success: false,
      error:
        `Repair intent "${derivedIntent}" has no executor yet, so it cannot be verified. ` +
        `Verifiable intents: ${VERIFIABLE_REPAIR_INTENTS.join(", ")}`,
    };
  }

  return { success: true, payload, repairIntent: derivedIntent };
}

// ─── Builder ────────────────────────────────────────────────

/**
 * Build the append-only `revision_events` row for a repair verification.
 *
 * Pure and deterministic apart from the injected timestamp.
 * Never invokes SM-2, mastery, or the legacy diagnostic engine.
 *
 * @param payload - A validated verification payload
 * @param repairIntent - The server-derived repair intent
 * @param now - Verification timestamp (injectable for tests)
 */
export function buildRepairVerificationEvent(
  payload: RepairVerificationPayload,
  repairIntent: RepairIntent,
  now: Date = new Date(),
): RepairVerificationEvent {
  const verificationCorrect =
    payload.verificationSelectedAnswer === payload.verificationCorrectAnswer;

  return {
    eventType: REPAIR_VERIFICATION_EVENT_TYPE,
    // SM-2 isolation: no quality signal, no MCQ correctness column.
    qualityRating: null,
    mcqCorrect: null,
    mcqQuestionIndex: null,
    eventMetadata: {
      requestId: payload.requestId,
      conceptId: payload.conceptId,
      failureReason: payload.failureReason,
      repairIntent,
      verificationCorrect,
      verificationSelectedAnswer: payload.verificationSelectedAnswer,
      verificationCorrectAnswer: payload.verificationCorrectAnswer,
      questionId: payload.questionContext?.questionId ?? null,
      questionIndex: payload.questionContext?.questionIndex ?? null,
      verificationQuestion: payload.verificationQuestion ?? null,
      verifiedAt: now.toISOString(),
    },
  };
}
